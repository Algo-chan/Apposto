/** Text in the language (English when it's missing); the key itself when no language has it. */
export function tr(lang, key, params = {}) {
  const template = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, k) => (params[k] == null ? '' : String(params[k])));
}
